export const GLYPH_W = 5;
export const GLYPH_H = 7;

/* Returns [[col,row], ...] of lit pixels for a line of text, plus its width in cells. */
export function layoutLine(text) {
  const pixels = [];
  let col = 0;
  for (const ch of text.toUpperCase()) {
    const g = G[ch] || G[" "];
    for (let r = 0; r < GLYPH_H; r++) {
      for (let c = 0; c < GLYPH_W; c++) if (g[r][c] === "#") pixels.push([col + c, r]);
    }
    col += GLYPH_W + 1;
  }
  return { pixels, width: Math.max(0, col - 1) };
}
